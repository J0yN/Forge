import React, { useState, useEffect } from 'react';
import { useProjectStore } from '../store/useProjectStore';
import { analyzeAndCreateProject } from '../services/aiService';
import { Project, Milestone, Task, RealityCheck, ProjectMemory } from '../types';
import {
  Flame,
  ArrowRight,
  Upload,
  FileText,
  X,
  Sparkles,
  Check,
  AlertCircle,
  Lightbulb,
} from 'lucide-react';

interface NewProjectViewProps {
  onNavigate: (path: string) => void;
}

const STAGES = [
  'Understanding your goal...',
  'Finding the outcome...',
  'Mapping dependencies...',
  'Checking assumptions...',
  'Building your roadmap...',
];

export const NewProjectView: React.FC<NewProjectViewProps> = ({ onNavigate }) => {
  const { createProject, settings } = useProjectStore();

  const [goalText, setGoalText] = useState('');
  const [attachmentName, setAttachmentName] = useState<string | null>(null);
  const [attachmentContent, setAttachmentContent] = useState<string>('');
  const [isSubmitting, setIsSubmitting] = useState(false);
  const [currentStageIndex, setCurrentStageIndex] = useState(0);
  const [errorMessage, setErrorMessage] = useState<string | null>(null);

  useEffect(() => {
    // Check if draft goal was carried from Onboarding or Dashboard
    const draft = sessionStorage.getItem('forge_draft_goal');
    if (draft) {
      setGoalText(draft);
      sessionStorage.removeItem('forge_draft_goal');
    }
  }, []);

  // Cycle through purposeful loading stages
  useEffect(() => {
    if (!isSubmitting) return;

    const interval = setInterval(() => {
      setCurrentStageIndex((prev) => {
        if (prev < STAGES.length - 1) {
          return prev + 1;
        }
        return prev;
      });
    }, 1100);

    return () => clearInterval(interval);
  }, [isSubmitting]);

  const handleFileUpload = (e: React.ChangeEvent<HTMLInputElement>) => {
    const file = e.target.files?.[0];
    if (!file) return;

    setAttachmentName(file.name);

    const reader = new FileReader();
    reader.onload = (event) => {
      const text = event.target?.result as string;
      setAttachmentContent(text ? text.slice(0, 5000) : `Attached file: ${file.name} (${file.size} bytes)`);
    };
    reader.onerror = () => {
      setAttachmentContent(`Attached file: ${file.name}`);
    };

    if (file.type.includes('text') || file.type.includes('json') || file.name.endsWith('.md')) {
      reader.readAsText(file);
    } else {
      setAttachmentContent(`Attachment metadata: ${file.name}, size: ${file.size} bytes, type: ${file.type}`);
    }
  };

  const handleRemoveAttachment = () => {
    setAttachmentName(null);
    setAttachmentContent('');
  };

  const handleForge = async (e: React.FormEvent) => {
    e.preventDefault();
    if (!goalText.trim() || isSubmitting) return;

    setIsSubmitting(true);
    setErrorMessage(null);
    setCurrentStageIndex(0);

    try {
      const result = await analyzeAndCreateProject({
        goalText: goalText.trim(),
        attachmentContent: attachmentContent || undefined,
        userContext: settings.profile,
      });

      const projectId = `proj-${Date.now()}`;
      const now = new Date().toISOString();

      // Normalize milestones and tasks
      const createdMilestones: Milestone[] = [];
      const createdTasks: Task[] = [];

      result.milestones.forEach((m, mIdx) => {
        const milestoneId = `ms-${projectId}-${mIdx + 1}`;
        const taskIds: string[] = [];

        m.tasks.forEach((t, tIdx) => {
          const taskId = `task-${projectId}-${mIdx + 1}-${tIdx + 1}`;
          taskIds.push(taskId);

          createdTasks.push({
            id: taskId,
            projectId,
            milestoneId,
            title: t.title,
            description: t.description || '',
            status: (mIdx === 0 && tIdx === 0 ? 'todo' : 'todo') as any,
            priority: (t.priority || 'high') as any,
            dependencies: [],
            estimatedEffort: t.estimatedEffort || '2-3 hours',
            completionCriteria: t.completionCriteria || [],
            deliverableSuggestions: t.deliverableSuggestions || [],
            createdAt: now,
            completedAt: null,
          });
        });

        createdMilestones.push({
          id: milestoneId,
          projectId,
          title: m.title,
          objective: m.objective,
          status: mIdx === 0 ? 'available' : 'locked',
          order: mIdx + 1,
          dependencies: mIdx === 0 ? [] : [`ms-${projectId}-${mIdx}`],
          completionCriteria: m.completionCriteria || [],
          tasks: taskIds,
        });
      });

      const createdProject: Project = {
        id: projectId,
        title: result.title || goalText.slice(0, 40),
        description: result.description || 'Actionable roadmap generated by FORGE.',
        goal: {
          outcome: result.goal?.outcome || goalText,
          successCriteria: result.goal?.successCriteria || [],
          category: result.goal?.category || 'business',
        },
        constraints: result.constraints || [],
        status: 'active',
        progress: 0,
        currentMilestoneId: createdMilestones[0]?.id || '',
        currentTaskId: createdTasks[0]?.id || null,
        createdAt: now,
        updatedAt: now,
      };

      const createdRealityCheck: RealityCheck = {
        id: `rc-${projectId}`,
        projectId,
        overallRisk: result.realityCheck?.overallRisk || 'moderate',
        summary: result.realityCheck?.summary || 'Project initialized with structured checks.',
        strengths: result.realityCheck?.strengths || [],
        concerns: (result.realityCheck?.concerns || []).map((c, i) => ({
          id: `c-${i + 1}`,
          severity: c.severity || 'moderate',
          title: c.title,
          reason: c.reason,
          evidence: c.evidence,
          recommendation: c.recommendation,
        })),
        missingInformation: result.realityCheck?.missingInformation || [],
        recommendations: result.realityCheck?.recommendations || [],
        updatedAt: now,
      };

      const createdMemory: ProjectMemory = {
        id: `mem-${projectId}`,
        projectId,
        facts: (result.memory?.facts || []).map((f) => ({
          key: f.key,
          value: f.value,
          confidence: f.confidence || 'high',
        })),
        decisions: (result.memory?.decisions || []).map((d) => ({
          decision: d.decision,
          reason: d.reason,
          date: d.date || now.split('T')[0],
        })),
        constraints: result.memory?.constraints || [],
        preferences: result.memory?.preferences || [],
      };

      createProject({
        project: createdProject,
        milestones: createdMilestones,
        tasks: createdTasks,
        realityCheck: createdRealityCheck,
        memory: createdMemory,
      });

      // Redirect directly to the newly forged project dashboard
      onNavigate(`/app/projects/${projectId}`);
    } catch (err: any) {
      console.error('Failed to create project:', err);
      setIsSubmitting(false);
      setErrorMessage(
        err.message || "FORGE couldn't complete that step. Your project is safe. Please try again."
      );
    }
  };

  const sampleIdeas = [
    'I want to launch a small clothing brand with ₹50,000.',
    'Build my first developer micro-SaaS and get 10 paying users.',
    'Prepare for a Senior Product Manager interview loop in 3 weeks.',
    'Learn Python for data analysis in 60 days with 3 portfolio projects.',
  ];

  return (
    <div className="p-6 md:p-12 max-w-4xl mx-auto space-y-8 animate-in fade-in duration-200">
      
      {/* Top Header */}
      <div>
        <div className="text-xs font-mono uppercase tracking-wider text-[#F5A524] font-semibold">
          NEW EXECUTION PROJECT
        </div>
        <h1 className="font-display text-2xl md:text-4xl font-extrabold text-[#F5F7FA] mt-1">
          What are you trying to accomplish?
        </h1>
        <p className="text-sm text-[#9AA4B2] mt-2">
          Tell FORGE what you want to achieve. We infer the constraints, map dependencies, check assumptions, and build your execution roadmap.
        </p>
      </div>

      {/* Main Creation Card */}
      {!isSubmitting ? (
        <form onSubmit={handleForge} className="space-y-6">
          <div className="p-6 rounded-2xl bg-[#12161B] border border-[#252B33] space-y-4 shadow-xl focus-within:border-[#F5A524]/60 transition-colors">
            <textarea
              rows={6}
              value={goalText}
              onChange={(e) => setGoalText(e.target.value)}
              placeholder="I want to..."
              className="w-full bg-transparent text-base md:text-lg text-[#F5F7FA] placeholder-[#9AA4B2]/40 focus:outline-none resize-none leading-relaxed"
              autoFocus
            />

            {/* Attachment preview if present */}
            {attachmentName && (
              <div className="flex items-center justify-between p-3 rounded-lg bg-[#181D23] border border-[#252B33] text-xs">
                <div className="flex items-center gap-2 text-[#F5F7FA]">
                  <FileText className="w-4 h-4 text-[#F5A524]" />
                  <span className="font-medium truncate max-w-xs">{attachmentName}</span>
                </div>
                <button
                  type="button"
                  onClick={handleRemoveAttachment}
                  className="p-1 rounded text-[#9AA4B2] hover:text-[#EF6461] hover:bg-[#252B33] transition-colors"
                >
                  <X className="w-4 h-4" />
                </button>
              </div>
            )}

            {/* Bottom Form Toolbar */}
            <div className="pt-4 border-t border-[#252B33] flex flex-col sm:flex-row items-stretch sm:items-center justify-between gap-4">
              <label className="flex items-center gap-2 text-xs font-medium text-[#9AA4B2] hover:text-[#F5F7FA] cursor-pointer transition-colors px-2 py-1.5 rounded-lg hover:bg-[#181D23] w-fit">
                <Upload className="w-4 h-4 text-[#F5A524]" />
                <span>Attach doc, spec, or image (optional)</span>
                <input
                  type="file"
                  onChange={handleFileUpload}
                  className="hidden"
                  accept=".pdf,.txt,.md,.json,.doc,.docx,image/*"
                />
              </label>

              <button
                type="submit"
                disabled={!goalText.trim()}
                className="flex items-center justify-center gap-2 px-7 py-3 rounded-xl bg-[#F5A524] text-[#0B0D10] text-sm font-bold hover:bg-[#F5A524]/90 disabled:opacity-40 disabled:cursor-not-allowed transition-all shadow-md shadow-[#F5A524]/20 cursor-pointer"
              >
                <span>Forge this goal</span>
                <ArrowRight className="w-4 h-4 stroke-[2.5]" />
              </button>
            </div>
          </div>

          {/* Quick Examples */}
          <div className="space-y-2">
            <div className="text-xs uppercase tracking-wider text-[#9AA4B2] font-semibold flex items-center gap-1.5">
              <Lightbulb className="w-3.5 h-3.5 text-[#F5A524]" />
              <span>Examples to try:</span>
            </div>
            <div className="grid grid-cols-1 sm:grid-cols-2 gap-2">
              {sampleIdeas.map((idea, idx) => (
                <button
                  key={idx}
                  type="button"
                  onClick={() => setGoalText(idea)}
                  className="p-3 rounded-lg bg-[#12161B] border border-[#252B33] text-left text-xs text-[#9AA4B2] hover:text-[#F5F7FA] hover:border-[#374151] transition-colors truncate"
                >
                  "{idea}"
                </button>
              ))}
            </div>
          </div>

          {/* Error Message */}
          {errorMessage && (
            <div className="p-4 rounded-xl bg-[#EF6461]/10 border border-[#EF6461]/30 flex items-center justify-between text-xs text-[#EF6461]">
              <div className="flex items-center gap-2">
                <AlertCircle className="w-4 h-4 shrink-0" />
                <span>{errorMessage}</span>
              </div>
              <button
                type="button"
                onClick={() => setErrorMessage(null)}
                className="underline hover:text-white ml-2"
              >
                Dismiss
              </button>
            </div>
          )}
        </form>
      ) : (
        /* Purposeful Stage Progress Experience (Section 12 & 37) */
        <div className="p-8 sm:p-12 rounded-2xl bg-[#12161B] border border-[#252B33] shadow-2xl text-center space-y-8 animate-in fade-in duration-200">
          <div className="relative w-16 h-16 mx-auto">
            <div className="w-16 h-16 rounded-2xl bg-[#F5A524]/10 border border-[#F5A524]/30 flex items-center justify-center text-[#F5A524]">
              <Flame className="w-8 h-8 animate-pulse" />
            </div>
          </div>

          <div className="space-y-2">
            <h2 className="font-display text-2xl font-bold text-[#F5F7FA]">
              Forging Execution Architecture
            </h2>
            <p className="text-sm text-[#9AA4B2] max-w-md mx-auto">
              Analyzing constraints, removing ambiguity, and generating your high-leverage milestones.
            </p>
          </div>

          {/* Sequential Stage Checklist */}
          <div className="max-w-sm mx-auto space-y-3 text-left">
            {STAGES.map((stage, idx) => {
              const isPast = currentStageIndex > idx;
              const isCurrent = currentStageIndex === idx;

              return (
                <div
                  key={idx}
                  className={`flex items-center gap-3 p-3 rounded-lg border transition-all ${
                    isPast
                      ? 'bg-[#181D23] border-[#35C98A]/30 text-[#35C98A]'
                      : isCurrent
                      ? 'bg-[#181D23] border-[#F5A524] text-[#F5F7FA] shadow-sm'
                      : 'bg-[#0B0D10] border-[#252B33] text-[#9AA4B2]/40'
                  }`}
                >
                  <div
                    className={`w-5 h-5 rounded-full flex items-center justify-center text-xs font-mono font-bold ${
                      isPast
                        ? 'bg-[#35C98A] text-[#0B0D10]'
                        : isCurrent
                        ? 'bg-[#F5A524] text-[#0B0D10] animate-pulse'
                        : 'border border-[#252B33]'
                    }`}
                  >
                    {isPast ? <Check className="w-3.5 h-3.5 stroke-[3]" /> : idx + 1}
                  </div>
                  <span className="text-xs font-medium">{stage}</span>
                </div>
              );
            })}
          </div>

          <div className="text-[11px] text-[#9AA4B2] font-mono">
            Powered by Gemini 3.8 Flash Execution Engine
          </div>
        </div>
      )}
    </div>
  );
};
